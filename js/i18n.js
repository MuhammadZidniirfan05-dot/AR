function getCurrentLang() {
  try {
    const saved = localStorage.getItem("ar-organ-lang");
    if (saved === "en" || saved === "id") {
      return saved;
    }
  } catch (err) {
    // Abaikan jika localStorage tidak tersedia
  }
  return "id";
}

function t(key, vars) {
  const lang = getCurrentLang();
  const dict = I18N[lang] || I18N.id;
  let text = dict[key] !== undefined ? dict[key] : (I18N.id[key] || key);
  if (vars && typeof vars === "object") {
    Object.keys(vars).forEach(k => {
      text = text.split(`{${k}}`).join(String(vars[k]));
    });
  }
  return text;
}

function getOrganText(organ, lang) {
  const activeLang = lang || getCurrentLang();
  const useEn = activeLang === "en" && organ.en;
  const src = useEn ? organ.en : organ;

  const hotspots = Array.isArray(organ.hotspots)
    ? organ.hotspots.map(h => {
        const hEn = useEn && h.en ? h.en : null;
        return {
          id: h.id,
          label: hEn && hEn.label ? hEn.label : h.label,
          info: hEn && hEn.info ? hEn.info : h.info,
          position: h.position,
          normal: h.normal
        };
      })
    : [];

  const penyakit = Array.isArray(src.penyakit)
    ? src.penyakit.map(p => ({
        nama: p.nama,
        info: p.info
      }))
    : (Array.isArray(organ.penyakit)
        ? organ.penyakit.map(p => {
            const pEn = useEn && p.en ? p.en : p;
            return {
              nama: pEn.nama,
              info: pEn.info
            };
          })
        : []);

  return {
    id: organ.id,
    nama: src.nama || organ.nama,
    ringkas: src.ringkas || organ.ringkas,
    deskripsi: src.deskripsi || organ.deskripsi,
    fungsi: Array.isArray(src.fungsi) ? src.fungsi : organ.fungsi,
    fakta: src.fakta || organ.fakta,
    penyakit: penyakit,
    tipsSehat: Array.isArray(src.tipsSehat) ? src.tipsSehat : organ.tipsSehat,
    hotspots: hotspots
  };
}

function getQuizText(item, lang) {
  const activeLang = lang || getCurrentLang();
  const useEn = activeLang === "en" && item.en;
  const src = useEn ? item.en : item;
  return {
    organId: item.organId,
    pertanyaan: src.pertanyaan || item.pertanyaan,
    pilihan: Array.isArray(src.pilihan) ? src.pilihan : item.pilihan,
    jawaban: item.jawaban,
    penjelasan: src.penjelasan || item.penjelasan
  };
}

function applyTranslations(lang) {
  const activeLang = lang === "en" ? "en" : "id";
  try {
    localStorage.setItem("ar-organ-lang", activeLang);
  } catch (err) {
    // Abaikan jika localStorage tidak tersedia
  }

  document.documentElement.lang = activeLang;

  const textNodes = document.querySelectorAll("[data-i18n]");
  textNodes.forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (key) {
      el.textContent = t(key);
    }
  });

  const placeholderNodes = document.querySelectorAll("[data-i18n-placeholder]");
  placeholderNodes.forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) {
      el.setAttribute("placeholder", t(key));
    }
  });

  const ariaNodes = document.querySelectorAll("[data-i18n-aria-label]");
  ariaNodes.forEach(el => {
    const key = el.getAttribute("data-i18n-aria-label");
    if (key) {
      el.setAttribute("aria-label", t(key));
    }
  });

  const langBtn = document.getElementById("lang-toggle");
  if (langBtn) {
    const isEn = activeLang === "en";
    langBtn.textContent = isEn ? "ID" : "EN";
    langBtn.setAttribute(
      "aria-label",
      isEn ? "Ganti ke Bahasa Indonesia" : "Switch to English"
    );
    langBtn.setAttribute(
      "title",
      isEn ? "Ganti ke Bahasa Indonesia" : "Switch to English"
    );
  }

  if (typeof applyTheme === "function") {
    const currentTheme =
      document.documentElement.dataset.theme ||
      (typeof getPreferredTheme === "function" ? getPreferredTheme() : "light");
    applyTheme(currentTheme);
  }

  document.dispatchEvent(
    new CustomEvent("ar-lang-change", { detail: { lang: activeLang } })
  );
}

function initI18n() {
  applyTranslations(getCurrentLang());
  const langBtn = document.getElementById("lang-toggle");
  if (!langBtn) {
    return;
  }
  langBtn.addEventListener("click", () => {
    const nextLang = getCurrentLang() === "en" ? "id" : "en";
    applyTranslations(nextLang);
  });
}

if (typeof document !== "undefined") {
  initI18n();
}
